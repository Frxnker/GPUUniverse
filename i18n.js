let currentLang = localStorage.getItem('gpu_lang') || 'es';

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    window.currentLang = lang;
    localStorage.setItem('gpu_lang', lang);
    applyTranslations();
    updateLangUI(lang);
    document.documentElement.lang = lang;
    if (typeof window.renderAll === 'function') {
      window.renderAll();
    }
  }
}

function updateLangUI(lang) {
  const currentFlag = document.getElementById('current-flag');
  const currentLangText = document.getElementById('current-lang');
  if (currentFlag) {
    const flagCode = lang === 'en' ? 'us' : lang;
    currentFlag.src = `https://flagcdn.com/w20/${flagCode}.png`;
  }
  if (currentLangText) {
    currentLangText.textContent = lang.toUpperCase();
  }
}

function t(keyPath) {
  const keys = keyPath.split('.');
  let value = translations[currentLang];
  for (let key of keys) {
    if (value[key] === undefined) return keyPath;
    value = value[key];
  }
  return value;
}
window.t = t;
window.currentLang = currentLang;

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    
    // Si es un input, modificar el placeholder, sino el textContent/innerHTML
    if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
      el.placeholder = translation;
    } else {
      // Usamos innerHTML en caso de que haya saltos de línea <br> incluidos
      el.innerHTML = translation;
    }
  });
}

// Inicializar
function initI18n() {
  applyTranslations();
  updateLangUI(currentLang);
  document.documentElement.lang = currentLang;
  
  const switcher = document.querySelector('.lang-switcher');
  const btn = document.getElementById('lang-btn');
  const options = document.querySelectorAll('.lang-option');

  if (btn && switcher) {
    btn.onclick = (e) => {
      e.stopPropagation();
      switcher.classList.toggle('active');
    };
  }

  options.forEach(opt => {
    opt.onclick = () => {
      const lang = opt.getAttribute('data-value');
      setLanguage(lang);
      switcher.classList.remove('active');
    };
  });

  // Cerrar al hacer clic fuera
  document.addEventListener('click', () => {
    if (switcher) switcher.classList.remove('active');
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
